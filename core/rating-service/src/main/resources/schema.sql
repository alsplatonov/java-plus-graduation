-- Оценки событий. Событие, автор и оценивающий пользователь принадлежат другим сервисам,
-- поэтому хранятся только идентификаторы (без внешних ключей)
-- author_id (инициатор события) сохраняется при оценке, чтобы считать рейтинг авторов без обращения к событиям
CREATE TABLE IF NOT EXISTS event_ratings
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id  BIGINT      NOT NULL,
    user_id   BIGINT      NOT NULL,
    author_id BIGINT      NOT NULL,
    type      VARCHAR(20) NOT NULL,
    created   TIMESTAMP   NOT NULL,
    CONSTRAINT uq_event_rating UNIQUE (event_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_event_ratings_event ON event_ratings (event_id);
CREATE INDEX IF NOT EXISTS idx_event_ratings_author ON event_ratings (author_id);
